#!/usr/bin/env node
'use strict';
// Regenerates js/ai-context.js from SONG_SHAPE_AI_CONTEXT.md and .json so the
// browser (file://, no fetch) and the CLI use the same default context.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..');
const md = fs.readFileSync(path.join(ROOT, 'SONG_SHAPE_AI_CONTEXT.md'), 'utf8');
const json = JSON.parse(fs.readFileSync(path.join(ROOT, 'SONG_SHAPE_AI_CONTEXT.json'), 'utf8'));
const sha = crypto.createHash('sha256').update(md, 'utf8').digest('hex');
const out = '/* GENERATED by tools/build-ai-context.js from SONG_SHAPE_AI_CONTEXT.md / .json. Do not edit by hand. */\n' +
  '(function (root) {\n  "use strict";\n' +
  '  var api = {\n' +
  '    AI_CONTEXT_DEFAULT_TEXT: ' + JSON.stringify(md) + ',\n' +
  '    AI_CONTEXT_DEFAULT_SHA256: ' + JSON.stringify(sha) + ',\n' +
  '    AI_CONTEXT_VERSION: ' + JSON.stringify(json.context_version) + ',\n' +
  '    AI_CONTEXT_JSON: ' + JSON.stringify(json) + '\n  };\n' +
  '  root.SongShape = root.SongShape || {};\n' +
  '  Object.keys(api).forEach(function (k) { root.SongShape[k] = api[k]; });\n' +
  '  if (typeof module !== "undefined" && module.exports) module.exports = api;\n' +
  '})(typeof globalThis !== "undefined" ? globalThis : this);\n';
fs.writeFileSync(path.join(ROOT, 'js', 'ai-context.js'), out);
console.log('Wrote js/ai-context.js (context ' + json.context_version + ', sha256 ' + sha.slice(0, 12) + '…)');
